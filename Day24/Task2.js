// Types of JavaScript Errors
// 1. Syntax Error
// Mistakes in writing code (grammar errors).

// Example:

// if (a == 10 {
//   console.log(a);
// }

// 2. Runtime Error
// Errors that happen while the program is running.

// Example:

// let obj = null;
// console.log(obj.name); // cannot read property 'name'

// 3. Logical Error
// Program runs, but gives wrong output due to wrong logic.

// Example:

// let sum = 10 - 5; // should be + but used -